/**
 * Copies Nawaz emoji/sticker packs into assets/chat and generates
 * constants/chatPickerAssets.generated.ts for Metro static requires.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const NAWAZ = path.join(ROOT, 'Nawaz', 'Nawaz');
const OUT_ROOT = path.join(ROOT, 'assets', 'chat');
const GENERATED = path.join(ROOT, 'constants', 'chatPickerAssets.generated.ts');

const EMOJI_CATEGORIES = [
  { id: 'couple', label: 'Couple', sourceDir: 'couple' },
  { id: 'hearty', label: 'Hearty', sourceDir: 'Hearty' },
  { id: 'smiley', label: 'Smiley', sourceDir: 'smiley' },
];

const STICKER_CATEGORIES = [
  { id: 'couples', label: 'Couples', sourceDir: 'Couples' },
  { id: 'cupid', label: 'Cupid', sourceDir: 'Cupid' },
  { id: 'slang', label: 'Slang', sourceDir: 'Slang' },
];

function listPngFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => name.toLowerCase().endsWith('.png'))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));
}

function copyCategoryAssets({ type, category }) {
  const sourceDir = path.join(NAWAZ, type === 'emoji' ? 'Emojis' : 'Stickers', category.sourceDir);
  const targetDir = path.join(OUT_ROOT, `${type}s`, category.id);
  fs.mkdirSync(targetDir, { recursive: true });

  const files = listPngFiles(sourceDir);
  const assets = files.map((file, index) => {
    const id = String(index + 1).padStart(3, '0');
    const targetName = `${id}.png`;
    fs.copyFileSync(path.join(sourceDir, file), path.join(targetDir, targetName));
    const rel = `../assets/chat/${type}s/${category.id}/${targetName}`;
    return {
      id: `${type}-${category.id}-${id}`,
      body: `asset:${type}:${category.id}:${id}`,
      label: `${category.label} ${Number(id)}`,
      category: category.id,
      rel,
    };
  });

  return assets;
}

function emitAssets(type, categories, assetsByCategory) {
  const lines = [];
  const allAssets = [];

  categories.forEach((category) => {
    const assets = assetsByCategory[category.id] ?? [];
    allAssets.push(...assets);
    lines.push(`export const CHAT_${type.toUpperCase()}_${category.id.toUpperCase()}_ASSETS = [`);
    assets.forEach((asset) => {
      lines.push(`  {`);
      lines.push(`    id: '${asset.id}',`);
      lines.push(`    body: '${asset.body}',`);
      lines.push(`    label: '${asset.label}',`);
      lines.push(`    category: '${asset.category}',`);
      lines.push(`    source: require('${asset.rel}'),`);
      lines.push(`  },`);
    });
    lines.push(`] as ChatPickerAsset[];`);
    lines.push('');
  });

  lines.push(`export const CHAT_${type.toUpperCase()}_CATEGORIES = [`);
  categories.forEach((category) => {
    lines.push(`  { id: '${category.id}', label: '${category.label}' },`);
  });
  lines.push(`] as const;`);
  lines.push('');

  lines.push(`export const CHAT_${type.toUpperCase()}_ASSETS: ChatPickerAsset[] = [`);
  allAssets.forEach((asset) => {
    lines.push(`  ...CHAT_${type.toUpperCase()}_${asset.category.toUpperCase()}_ASSETS,`);
  });
  lines.push(`];`);
  lines.push('');

  return lines;
}

function main() {
  if (!fs.existsSync(NAWAZ)) {
    console.error('Nawaz asset folder not found:', NAWAZ);
    process.exit(1);
  }

  const emojiByCategory = {};
  EMOJI_CATEGORIES.forEach((category) => {
    emojiByCategory[category.id] = copyCategoryAssets({ type: 'emoji', category });
    console.log(`Emojis/${category.label}: ${emojiByCategory[category.id].length}`);
  });

  const stickerByCategory = {};
  STICKER_CATEGORIES.forEach((category) => {
    stickerByCategory[category.id] = copyCategoryAssets({ type: 'sticker', category });
    console.log(`Stickers/${category.label}: ${stickerByCategory[category.id].length}`);
  });

  const output = [
    '// Auto-generated by scripts/generate-chat-picker-assets.js — do not edit by hand.',
    '',
    "export type ChatPickerAsset = {",
    '  id: string;',
    '  body: string;',
    '  label: string;',
    '  category: string;',
    '  source: number;',
    '};',
    '',
    ...emitAssets('emoji', EMOJI_CATEGORIES, emojiByCategory),
    ...emitAssets('sticker', STICKER_CATEGORIES, stickerByCategory),
  ].join('\n');

  fs.writeFileSync(GENERATED, `${output}\n`);
  console.log('Wrote', path.relative(ROOT, GENERATED));
}

main();
